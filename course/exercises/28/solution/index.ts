export const VEC_INDEX = "northbank-guides-vec-v1";
export const VEC_DATA_SOURCE = "northbank-guides-blob";
export const VEC_SKILLSET = "northbank-guides-vectorize";
export const VEC_INDEXER = "northbank-guides-indexer";
export const GUIDES_FOLDER = "guides/";
export const GUIDES_BLOB = `${GUIDES_FOLDER}northbank-guides.json`;
export const SPLIT_SKILL = "#Microsoft.Skills.Text.SplitSkill";
export const EMBEDDING_SKILL = "#Microsoft.Skills.Text.AzureOpenAIEmbeddingSkill";
const VECTORIZER = "northbank-openai";

type ModelEnv = Pick<Required<AzureEnv>, "openaiEndpoint" | "embeddingDeployment" | "embeddingModel" | "dimensions">;
export interface Mapping {
  name: string;
  source: string;
}
export interface VectorSkillset {
  name: string;
  description?: string;
  skills: Record<string, any>[];
  indexProjections: {
    selectors: { targetIndexName: string; parentKeyFieldName: string; sourceContext: string; mappings: Mapping[] }[];
    parameters: { projectionMode?: "skipIndexingParentDocuments" | "includeIndexingParentDocuments" };
  };
}
export interface Problem {
  rule: "model" | "dimensions" | "deployment" | "resource" | "keyless" | "split" | "projection" | "key" | "context";
  message: string;
}

const trimSlash = (uri: string) => uri.replace(/\/+$/, "");

/**
 * One search document per chunk. Governance fields repeat on every chunk so filters still work; chunk_id is generated by
 * the indexer (keyword analyzer), parent_id links a chunk to its guide.
 */
export function vectorIndex(env: ModelEnv): IndexDefinition {
  const text = (name: string, searchable: boolean, filterable: boolean, facetable = false) => ({ name, type: "Edm.String", searchable, filterable, retrievable: true, sortable: false, facetable });
  const date = (name: string) => ({ name, type: "Edm.DateTimeOffset", searchable: false, filterable: true, retrievable: true, sortable: true, facetable: false });
  return {
    name: VEC_INDEX,
    description: "Northbank guides, chunked and embedded by the service. Only approved, in-date chunks may reach a model.",
    fields: [
      { name: "chunk_id", type: "Edm.String", key: true, searchable: true, filterable: true, retrievable: true, sortable: true, facetable: false, analyzer: "keyword" },
      text("parent_id", false, true),
      text("title", true, false),
      text("chunk", true, false),
      text("sourceUri", false, true),
      text("status", false, true, true),
      date("effectiveDate"),
      date("expiryDate"),
      { name: "chunkVector", type: "Collection(Edm.Single)", searchable: true, retrievable: false, dimensions: env.dimensions, vectorSearchProfile: "northbank-guides-profile" },
    ],
    vectorSearch: {
      algorithms: [{ name: "northbank-hnsw", kind: "hnsw", hnswParameters: { m: 4, efConstruction: 400, efSearch: 500, metric: "cosine" } }],
      profiles: [{ name: "northbank-guides-profile", algorithm: "northbank-hnsw", vectorizer: VECTORIZER }],
      // No apiKey: the search service's managed identity calls the deployment at query time.
      vectorizers: [{ name: VECTORIZER, kind: "azureOpenAI", azureOpenAIParameters: { resourceUri: trimSlash(env.openaiEndpoint), deploymentId: env.embeddingDeployment, modelName: env.embeddingModel } }],
    },
  };
}

/** Split each guide into overlapping pages, embed each page, and project every page to its own search document. */
export function vectorSkillset(env: ModelEnv, maximumPageLength = 600, pageOverlapLength = 150): VectorSkillset {
  const fromParent = ["title", "sourceUri", "status", "effectiveDate", "expiryDate"].map((name) => ({ name, source: `/document/${name}` }));
  return {
    name: VEC_SKILLSET,
    description: "Chunk Northbank guides and embed each chunk with the course's Azure OpenAI deployment.",
    skills: [
      {
        "@odata.type": SPLIT_SKILL,
        name: "split-pages",
        context: "/document",
        textSplitMode: "pages",
        maximumPageLength,
        pageOverlapLength,
        inputs: [{ name: "text", source: "/document/body" }],
        outputs: [{ name: "textItems", targetName: "pages" }],
      },
      {
        "@odata.type": EMBEDDING_SKILL,
        name: "embed-pages",
        context: "/document/pages/*",
        resourceUri: trimSlash(env.openaiEndpoint),
        deploymentId: env.embeddingDeployment,
        modelName: env.embeddingModel,
        dimensions: env.dimensions,
        inputs: [{ name: "text", source: "/document/pages/*" }],
        outputs: [{ name: "embedding", targetName: "vector" }],
      },
    ],
    indexProjections: {
      selectors: [
        {
          targetIndexName: VEC_INDEX,
          parentKeyFieldName: "parent_id",
          sourceContext: "/document/pages/*",
          mappings: [{ name: "chunk", source: "/document/pages/*" }, { name: "chunkVector", source: "/document/pages/*/vector" }, ...fromParent],
        },
      ],
      parameters: { projectionMode: "skipIndexingParentDocuments" },
    },
  };
}

export function vectorIndexerDefinition(): Indexer {
  return {
    name: VEC_INDEXER,
    dataSourceName: VEC_DATA_SOURCE,
    targetIndexName: VEC_INDEX,
    skillsetName: VEC_SKILLSET,
    parameters: { configuration: { parsingMode: "jsonArray", indexedFileNameExtensions: ".json" } },
    fieldMappings: [],
  };
}

/** The blob's elements: whole guides, keyed by their own id. */
export function guideRecords(documents: FaqDocument[]): FaqDocument[] {
  return documents.map((d) => ({ ...d }));
}

/** Everything that must agree between the skillset, the index and its vectorizer for integrated vectorization to work. */
export function reviewIntegratedVectorization(index: IndexDefinition, skillset: VectorSkillset): Problem[] {
  const problems: Problem[] = [];
  const split = skillset.skills.find((s) => s["@odata.type"] === SPLIT_SKILL);
  const embed = skillset.skills.find((s) => s["@odata.type"] === EMBEDDING_SKILL);
  const selector = skillset.indexProjections.selectors.find((s) => s.targetIndexName === index.name);
  if (!split || !embed || !selector) {
    if (!split) problems.push({ rule: "split", message: "no Text Split skill" });
    if (!embed) problems.push({ rule: "model", message: "no Azure OpenAI Embedding skill" });
    if (!selector) problems.push({ rule: "projection", message: `no index projection targets ${index.name}` });
    return problems;
  }
  // Chunking.
  const max = split.maximumPageLength ?? 5000;
  const overlap = split.pageOverlapLength ?? 0;
  if (split.textSplitMode !== "pages") problems.push({ rule: "split", message: "use textSplitMode pages for chunks with a size limit" });
  if (max < 300 || max > 50000) problems.push({ rule: "split", message: `maximumPageLength must be 300–50000, got ${max}` });
  if (overlap < 0 || overlap * 2 >= max) problems.push({ rule: "split", message: `pageOverlapLength must be less than half of maximumPageLength, got ${overlap}` });
  // Contexts: the embedding runs once per page, and the projection makes one document per page.
  const pages = `${split.context}/${split.outputs[0].targetName ?? split.outputs[0].name}/*`;
  if (embed.context !== pages || embed.inputs[0]?.source !== pages) problems.push({ rule: "context", message: `the embedding skill must run on ${pages}` });
  if (selector.sourceContext !== pages) problems.push({ rule: "context", message: `the projection sourceContext must be ${pages}` });
  // Model, dimensions and endpoint must be the same at indexing time and at query time.
  const vectorField = index.fields.find((f) => isVector(f.type));
  const profile = index.vectorSearch?.profiles.find((p) => p.name === vectorField?.vectorSearchProfile);
  const vectorizer = index.vectorSearch?.vectorizers?.find((v) => v.name === profile?.vectorizer);
  const params = (vectorizer?.azureOpenAIParameters ?? {}) as Record<string, unknown>;
  if (!vectorizer) problems.push({ rule: "model", message: "the vector field's profile has no vectorizer, so text queries cannot be embedded" });
  else {
    if (params.modelName !== embed.modelName) problems.push({ rule: "model", message: `skill embeds with ${embed.modelName}, vectorizer with ${params.modelName}` });
    if (params.deploymentId !== embed.deploymentId) problems.push({ rule: "deployment", message: `skill uses deployment ${embed.deploymentId}, vectorizer ${params.deploymentId}` });
    if (trimSlash(String(params.resourceUri ?? "")) !== trimSlash(String(embed.resourceUri ?? ""))) problems.push({ rule: "resource", message: "skill and vectorizer call different Azure OpenAI resources" });
    if ("apiKey" in params) problems.push({ rule: "keyless", message: "the vectorizer has an apiKey; use the service's managed identity" });
  }
  if ("apiKey" in embed) problems.push({ rule: "keyless", message: "the embedding skill has an apiKey; use the service's managed identity" });
  if (vectorField?.dimensions !== embed.dimensions) problems.push({ rule: "dimensions", message: `skill produces ${embed.dimensions} dimensions, ${vectorField?.name} expects ${vectorField?.dimensions}` });
  // Keys and mappings.
  const key = index.fields.find((f) => f.key);
  if (key?.analyzer !== "keyword") problems.push({ rule: "key", message: "the chunk key field needs the keyword analyzer" });
  const parent = index.fields.find((f) => f.name === selector.parentKeyFieldName);
  if (!parent || parent.key || parent.type !== "Edm.String" || parent.filterable !== true)
    problems.push({ rule: "key", message: `${selector.parentKeyFieldName} must be a filterable Edm.String field that is not the key` });
  const mapped = new Set(selector.mappings.map((m) => m.name));
  if (key && mapped.has(key.name)) problems.push({ rule: "projection", message: `do not map the key field ${key.name}; the indexer generates it` });
  if (mapped.has(selector.parentKeyFieldName)) problems.push({ rule: "projection", message: `do not map ${selector.parentKeyFieldName}; it disrupts change tracking` });
  for (const m of selector.mappings) if (!index.fields.some((f) => f.name === m.name)) problems.push({ rule: "projection", message: `mapping targets unknown field ${m.name}` });
  for (const f of index.fields) if (!f.key && f.name !== selector.parentKeyFieldName && !mapped.has(f.name)) problems.push({ rule: "projection", message: `${f.name} is not mapped, so every chunk would have it empty` });
  if (skillset.indexProjections.parameters.projectionMode !== "skipIndexingParentDocuments")
    problems.push({ rule: "projection", message: "set projectionMode skipIndexingParentDocuments, or parent documents with empty chunks join the index" });
  return problems;
}

export interface TextVectorQuery {
  vectorQueries: { kind: "text"; text: string; fields: string; k: number }[];
  filter: string;
  select: string;
  top: number;
}

/** A text vector query: the service embeds the text with the field's vectorizer. Governed like every query. */
export function textVectorQuery(text: string, k: number, asOf: string): TextVectorQuery {
  if (!text.trim()) throw new Error("a text vector query needs text");
  if (!Number.isInteger(k) || k < 1) throw new RangeError("k must be a positive integer");
  return {
    vectorQueries: [{ kind: "text" as const, text, fields: "chunkVector", k }],
    filter: governanceFilter(asOf),
    select: "chunk_id,parent_id,title,chunk,sourceUri,status",
    top: k,
  };
}
